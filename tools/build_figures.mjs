// Bakes the figures' motion clips (js/world/toolbox/life/figures/rig.js) into figures/clips.js: per clip, per
// frame, per bone a rotation and a translation, quantised to 16 bits. The shader plays them from a float texture.
//
//   npm run figures            # rebuild clips.js after editing rig.js
//   npm run figures -- --check # fail if clips.js is stale (npm test does this too)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CLIPS, FRAMES, BONES, bakeClips } from '../js/world/toolbox/life/figures/rig.js';

const OUT = fileURLToPath(new URL('../js/world/toolbox/life/figures/clips.js', import.meta.url));

export function buildClipsModule() {
  const f = bakeClips(), q = new Int16Array(f.length);
  for (let i = 0; i < f.length; i++) {
    const k = i % 7;
    q[i] = Math.max(-32767, Math.min(32767, Math.round(k < 4 ? f[i] * 32767 : f[i] * 1000)));   // quaternion units, translation mm
  }
  const b64 = Buffer.from(q.buffer).toString('base64');
  const meta = CLIPS.map((c) => ({ name: c.name, seconds: c.seconds, stride: c.stride ? +c.stride.toFixed(4) : 0, rig: c.rig || 'person' }));
  const lines = b64.match(/.{1,120}/g).map((l) => `  '${l}'`).join(',\n');
  return `// Generated by npm run figures from rig.js. Do not edit.
// ${CLIPS.length} clips × ${FRAMES} frames × ${BONES} bones × (quaternion ×32767, translation mm), little-endian int16.
export const FRAMES = ${FRAMES};
export const BONES = ${BONES};
export const CLIP_META = ${JSON.stringify(meta)};
export const CLIP_DATA = [
${lines},
].join('');
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = buildClipsModule();
  if (process.argv.includes('--check')) {
    let old = ''; try { old = readFileSync(OUT, 'utf8'); } catch {}
    if (old !== text) { console.error('figures/clips.js is stale: run npm run figures'); process.exit(1); }
    console.log('figures/clips.js is up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${(text.length / 1024).toFixed(0)} KB, ${CLIPS.length} clips)`);
  }
}
