#!/usr/bin/env python3
"""The land beyond a map's ground: a coarse height grid out to ~45 km (user, 27 Nov 2026: matched shots against photos
of Kanab and the Coral Pink dunes — the photos' skylines are mountains 10–30 km off; the map's horizon was flat fog).

Writes routes/cities/<id>-far.json: a square grid (cellM, default 400 m) centred on the map's ground grid, heights in
metres as base64 Int16 (+ base). js/world/toolbox/landscape/far-terrain.js draws it as one mesh behind the streamed ground
(its distance compressed into the camera's range, the elevation angles kept). A warped map (tools/citylib/warp.py) is
sampled through its warp inside the warp's box and as the real land beyond it.

  python3 tools/far_terrain.py <city> [--radiusM 45000] [--cellM 400]
"""
import argparse, base64, json, math, os, sys
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from citylib import warp as _warp
from citylib.warp import Dem

ap = argparse.ArgumentParser()
ap.add_argument('city'); ap.add_argument('--radiusM', type=float, default=45000); ap.add_argument('--cellM', type=float, default=400); ap.add_argument('--offline', action='store_true')
a = ap.parse_args()

g = json.load(open(os.path.join(ROOT, 'routes', 'cities', f'{a.city}.json')))
import itertools
la = [v * 1e-6 for e in g['edges'] for v in itertools.accumulate(e['lat'])]
lo = [v * 1e-6 for e in g['edges'] for v in itertools.accumulate(e['lon'])]
clat, clon = (min(la) + max(la)) / 2, (min(lo) + max(lo)) / 2
ky, kx = 110540.0, 111320.0 * math.cos(math.radians(clat))
n = int(round(2 * a.radiusM / a.cellM)) + 1
xs = (np.arange(n) - (n - 1) / 2) * a.cellM
X, Z = np.meshgrid(xs, xs)            # (x east, z north here; rows run north → south below)
LAT = clat + Z[::-1] / ky; LON = clon + X / kx
dem = Dem()
H = dem(LAT, LON).astype(np.float64)
W = _warp.load(a.city)
if W:
    Hg, x0, y0, cell = W.height_grid()
    gx, gy = W.xy(LAT, LON)
    inside = (gx > x0 + cell) & (gx < x0 + cell * (Hg.shape[1] - 2)) & (gy > y0 + cell) & (gy < y0 + cell * (Hg.shape[0] - 2))
    H[inside] = W.elevation(LAT[inside], LON[inside])
    # (outside the warp's box the land is the real one; a 2 km blend at its edge)
    from scipy import ndimage
    d = ndimage.distance_transform_edt(inside) * a.cellM
    t = np.clip(d / 2000, 0, 1)
    real = dem(LAT, LON)
    H = real * (1 - t) + H * t
base = float(np.floor(H.min()))
q = np.clip(np.round(H - base), 0, 32767).astype('<i2')
out = {'format': 'bikefree-far-terrain-1', 'note': 'GENERATED by tools/far_terrain.py: the land beyond the ground grid (AWS Terrain Tiles; warped maps through their warp)',
       'attribution': 'Elevation: AWS Terrain Tiles (USGS 3DEP, NOAA and others)',
       'center': [round(clat, 6), round(clon, 6)], 'n': n, 'cellM': a.cellM, 'base': base, 'h': base64.b64encode(q.tobytes()).decode()}
path = os.path.join(ROOT, 'routes', 'cities', f'{a.city}-far.json')
json.dump(out, open(path, 'w'), separators=(',', ':'))
print(f'wrote {os.path.relpath(path, ROOT)}: {n}×{n} at {a.cellM:.0f} m, {H.min():.0f}–{H.max():.0f} m, {os.path.getsize(path) / 1024:.0f} KB')
