#!/usr/bin/env python3
"""Out West's rides on the warped map (user, 26 Nov 2026: the corridors' empty middles cut out and Kanab shrunk —
tools/citylib/warp.py; plan in the Project doc claude/out-west-squeeze-plan.md).

tools/city/outwest-routes.json keeps the rides in real coordinates, with a "warped" section for what changes when the map
is warped (a ride re-routed round a cut, or dropped). This step writes tools/city/outwest-routes.warped.json: the rides
with those changes made and every waypoint moved with its piece of the map. tools/pgh_routes.mjs reads that file when the
map's config has a warp; without one this step removes it.

  python3 tools/outwest_warp.py
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from citylib import warp

CITY = 'outwest'
src = os.path.join(ROOT, 'tools', 'city', f'{CITY}-routes.json')
out = os.path.join(ROOT, 'tools', 'city', f'{CITY}-routes.warped.json')
W = warp.load(CITY)
if not W:
    if os.path.exists(out): os.remove(out)
    print('no warp: rides as they are'); sys.exit(0)

R = json.load(open(src))
changes = R.pop('warped', {})
routes = []
for r in R['routes']:
    ch = changes.get(r['id'], {})
    if ch.get('drop'): print(f"  {r['id']}: dropped (its roads are cut out)"); continue
    r = {**r, **{k: v for k, v in ch.items() if k != 'note' or 'way' in ch}}
    r['way'] = [{**w, 'near': [round(v, 6) for v in W.fwd_any(*w['near'])]} for w in r['way']]
    routes.append(r)
R['routes'] = routes
R['note'] = 'GENERATED by tools/outwest_warp.py from outwest-routes.json (the warped map). ' + R.get('note', '')
json.dump(R, open(out, 'w'), indent=1)
print(f'wrote {os.path.relpath(out, ROOT)}: {len(routes)} rides')
