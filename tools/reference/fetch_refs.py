#!/usr/bin/env python3
"""Real-place photo reference for the graphics work (user, 27 Nov 2026: "improve the visuals … prove each change with
evidence"; the outside reference is the real places, not another game).

For each spot in tools/reference/spots.json, finds geotagged Wikimedia Commons photos within its radius, and keeps their
licence, author, date, place and a 1280 px copy (tools/.cache/ref/<map>/<file>.jpg — the pictures stay out of the repo;
the manifest, with attribution, is committed: tools/reference/<map>-photos.json).

  python3 tools/reference/fetch_refs.py [map …] [--refresh]   (without --refresh: only spots not yet in the manifest)
"""
import json, os, re, sys, time, urllib.parse, urllib.request
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
API = 'https://commons.wikimedia.org/w/api.php'
UA = {'User-Agent': 'bikefree-reference/0.1 (indoor cycling app; graphics reference; https://github.com/mattserrao/bikefree)'}


def get(params):
    url = API + '?' + urllib.parse.urlencode({**params, 'format': 'json'})
    for k in range(6):
        try:
            time.sleep(1.0)   # (Commons asks for gentle clients: one request a second, longer after a 429)
            return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60))
        except Exception as e:
            time.sleep(30 * (k + 1)); err = e
    raise err


def strip(html): return re.sub(r'<[^>]+>', '', html or '').strip()


def spot_photos(lat, lon, r, limit):
    d = get({'action': 'query', 'list': 'geosearch', 'gscoord': f'{lat}|{lon}', 'gsradius': min(10000, r), 'gslimit': limit, 'gsnamespace': 6})
    hits = d.get('query', {}).get('geosearch', [])
    out = []
    for k in range(0, len(hits), 40):
        titles = '|'.join(h['title'] for h in hits[k:k + 40])
        q = get({'action': 'query', 'titles': titles, 'prop': 'imageinfo', 'iiprop': 'url|extmetadata|size|mime', 'iiurlwidth': 1280})
        for p in q.get('query', {}).get('pages', {}).values():
            ii = (p.get('imageinfo') or [{}])[0]
            if ii.get('mime') not in ('image/jpeg', 'image/png'): continue
            m = ii.get('extmetadata', {})
            h = next(x for x in hits if x['title'] == p['title'])
            out.append({'title': p['title'], 'lat': h['lat'], 'lon': h['lon'], 'dist': round(h['dist']),
                        'thumb': ii.get('thumburl'), 'page': ii.get('descriptionurl'), 'w': ii.get('width'), 'h': ii.get('height'),
                        'license': strip(m.get('LicenseShortName', {}).get('value')), 'artist': strip(m.get('Artist', {}).get('value'))[:120],
                        'date': strip(m.get('DateTimeOriginal', {}).get('value'))[:40], 'desc': strip(m.get('ImageDescription', {}).get('value'))[:200]})
    return out


def main(maps):
    spots = json.load(open(os.path.join(ROOT, 'tools', 'reference', 'spots.json')))
    for mid in maps or spots:
        cache = os.path.join(ROOT, 'tools', '.cache', 'ref', mid); os.makedirs(cache, exist_ok=True)
        man = {'note': 'GENERATED by tools/reference/fetch_refs.py: geotagged Wikimedia Commons photos near each spot (licence and author kept; pictures cached, not committed)', 'spots': []}
        mpath = os.path.join(ROOT, 'tools', 'reference', f'{mid}-photos.json')
        have = {sp['id']: sp for sp in json.load(open(mpath))['spots']} if os.path.exists(mpath) and '--refresh' not in sys.argv else {}
        for sp in spots[mid]:
            if sp['id'] in have:   # (a spot already fetched is kept: new spots only — Commons rate-limits)
                man['spots'].append(have[sp['id']]); continue
            ph = spot_photos(sp['lat'], sp['lon'], sp.get('r', 1500), sp.get('limit', 60))
            for p in ph:
                name = re.sub(r'[^A-Za-z0-9._-]+', '_', p['title'][5:])[:90]
                if not name.lower().endswith(('.jpg', '.jpeg', '.png')): name += '.jpg'
                p['file'] = name
                path = os.path.join(cache, name)
                if p['thumb'] and not os.path.exists(path):
                    for k in range(5):
                        try:
                            open(path, 'wb').write(urllib.request.urlopen(urllib.request.Request(p['thumb'], headers=UA), timeout=60).read()); break
                        except Exception as e:
                            if k == 4: print('  !', name, e); p['file'] = None
                            time.sleep(8 * (k + 1))
                    time.sleep(1.0)
            man['spots'].append({**sp, 'photos': ph})
            print(f"{mid}/{sp['id']}: {len(ph)} photos")
        json.dump(man, open(os.path.join(ROOT, 'tools', 'reference', f'{mid}-photos.json'), 'w'), indent=1)


if __name__ == '__main__':
    main([a for a in sys.argv[1:] if not a.startswith('--')])
